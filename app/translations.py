class Translator:
    """Simple runtime translator for GUI labels."""

    def __init__(self, language: str = "tr") -> None:
        self.language = language if language in TRANSLATIONS else "tr"

    def set_language(self, language: str) -> None:
        if language in TRANSLATIONS:
            self.language = language

    def tr(self, key: str, **kwargs) -> str:
        text = TRANSLATIONS[self.language].get(key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except KeyError:
                return text
        return text

    def available_languages(self) -> Dict[str, str]:
        return {code: code.upper() for code in TRANSLATIONS}

    def current_language(self) -> str:
        return self.language

    def localize_error(self, message: str) -> str:
        lowered = message.lower()
        for key, translations in ERROR_TRANSLATIONS.items():
            if key in lowered:
                return translations.get(self.language, translations.get("en", message))
        return message
