#!/usr/bin/env node
/* eslint-disable no-console */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const dataDir = path.join(root, 'backend', 'database', 'world-data');
const outputSql = path.join(root, 'backend', 'database', 'seeds', 'generated', '002_world_bootstrap.sql');
const outputMap = path.join(root, 'backend', 'database', 'world-data', 'map-ready.json');

function readJson(fileName) {
  const fullPath = path.join(dataDir, fileName);
  return JSON.parse(fs.readFileSync(fullPath, 'utf8'));
}

function escapeSql(value) {
  if (value === null || value === undefined) {
    return 'NULL';
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

function numberOrDefault(value, fallback) {
  const num = Number(value);
  return Number.isFinite(num) ? num : fallback;
}

function buildSql(countries, regions, cities) {
  const lines = [];

  lines.push('-- Auto-generated by scripts/world/build-world-seed.js');
  lines.push('SET NAMES utf8mb4;');
  lines.push('START TRANSACTION;');
  lines.push('');

  lines.push('-- Countries (free dataset based bootstrap records)');
  countries.forEach(function (country) {
    lines.push(
      [
        'INSERT INTO countries (name, code, iso3, flag_emoji, treasury, total_population, average_happiness, military_power, economy_score, diplomacy_status, government_type, base_tax_rate, visa_policy_mode, work_permit_policy_mode, war_eligibility, is_playable, is_active, map_source, source_external_id)',
        'VALUES',
        '(',
        [
          escapeSql(country.name),
          escapeSql(country.code),
          escapeSql(country.iso3),
          escapeSql(country.flagEmoji),
          '5000000.00',
          '0',
          '55.00',
          '1000',
          '50.00',
          escapeSql('neutral'),
          escapeSql('republic'),
          '10.00',
          escapeSql('mixed'),
          escapeSql('regulated'),
          '1',
          country.playable ? '1' : '0',
          country.active ? '1' : '0',
          escapeSql('natural_earth'),
          escapeSql(country.sourceExternalId)
        ].join(', '),
        ');',
        'ON DUPLICATE KEY UPDATE',
        'name = VALUES(name), iso3 = VALUES(iso3), flag_emoji = VALUES(flag_emoji), is_playable = VALUES(is_playable), is_active = VALUES(is_active), source_external_id = VALUES(source_external_id);'
      ].join(' ')
    );
  });

  lines.push('');
  lines.push('-- Regions');
  regions.forEach(function (region) {
    lines.push(
      [
        'INSERT INTO regions (country_id, controlling_country_id, name, code, strategic_value, population, defense_level, infrastructure_level, battle_status, resource_production_score, city_count, geometry_geojson)',
        'SELECT c.id, c.id,',
        escapeSql(region.name) + ',',
        escapeSql(region.code) + ',',
        numberOrDefault(region.strategicValue, 10) + ',',
        '0, 1, 1,',
        escapeSql('peace') + ',',
        '0, 0, NULL',
        'FROM countries c',
        'WHERE c.code = ' + escapeSql(region.countryCode),
        'AND NOT EXISTS (SELECT 1 FROM regions r WHERE r.country_id = c.id AND r.code = ' + escapeSql(region.code) + ');'
      ].join(' ')
    );
  });

  lines.push('');
  lines.push('-- Cities');
  cities.forEach(function (city) {
    lines.push(
      [
        'INSERT INTO cities (country_id, region_id, name, latitude, longitude, population, economy_score, infrastructure_score, safety_score, education_score, healthcare_score, transport_score, local_treasury, development_level, housing_level, employment_rate, airport_level, industry_level, is_capital)',
        'SELECT c.id, r.id,',
        escapeSql(city.name) + ',',
        numberOrDefault(city.latitude, 0).toFixed(7) + ',',
        numberOrDefault(city.longitude, 0).toFixed(7) + ',',
        numberOrDefault(city.population, 0) + ',',
        '50.00, 50.00, 50.00, 50.00, 50.00, 50.00,',
        '500000.00, 1, 1, 65.00, 1, 1,',
        city.isCapital ? '1' : '0',
        'FROM countries c',
        'JOIN regions r ON r.country_id = c.id',
        'WHERE c.code = ' + escapeSql(city.countryCode),
        'AND r.code = ' + escapeSql(city.regionCode),
        'AND NOT EXISTS (SELECT 1 FROM cities ci WHERE ci.country_id = c.id AND ci.region_id = r.id AND ci.name = ' + escapeSql(city.name) + ');'
      ].join(' ')
    );
  });

  lines.push('');
  lines.push('-- Capital mapping');
  countries.forEach(function (country) {
    lines.push(
      'UPDATE countries c JOIN cities ci ON ci.country_id = c.id AND ci.name = ' + escapeSql(country.capitalCity) +
      ' SET c.capital_city_id = ci.id WHERE c.code = ' + escapeSql(country.code) + ';'
    );
  });

  lines.push('');
  lines.push('-- Aggregate values bootstrap');
  lines.push('UPDATE countries c');
  lines.push('LEFT JOIN (');
  lines.push('  SELECT country_id, SUM(population) AS total_population, COUNT(*) AS city_count FROM cities GROUP BY country_id');
  lines.push(') cityAgg ON cityAgg.country_id = c.id');
  lines.push('SET c.total_population = IFNULL(cityAgg.total_population, 0), c.economy_score = 55.00, c.military_power = 1200;');
  lines.push('');
  lines.push('UPDATE regions r');
  lines.push('LEFT JOIN (SELECT region_id, COUNT(*) AS city_count, SUM(population) AS pop FROM cities GROUP BY region_id) agg ON agg.region_id = r.id');
  lines.push('SET r.city_count = IFNULL(agg.city_count, 0), r.population = IFNULL(agg.pop, 0);');
  lines.push('');
  lines.push('COMMIT;');
  lines.push('');

  return lines.join('\n');
}

function buildMapReady(countries, regions, cities) {
  const countriesMap = {};
  countries.forEach(function (country) {
    countriesMap[country.code] = {
      code: country.code,
      iso3: country.iso3,
      name: country.name,
      flagEmoji: country.flagEmoji,
      source: {
        provider: 'natural_earth',
        countryExternalId: country.sourceExternalId
      },
      regions: []
    };
  });

  regions.forEach(function (region) {
    if (!countriesMap[region.countryCode]) return;
    countriesMap[region.countryCode].regions.push({
      code: region.code,
      name: region.name,
      strategicValue: numberOrDefault(region.strategicValue, 10),
      sourceExternalId: region.sourceExternalId,
      cities: []
    });
  });

  cities.forEach(function (city) {
    var country = countriesMap[city.countryCode];
    if (!country) return;

    var region = country.regions.find(function (r) {
      return r.code === city.regionCode;
    });

    if (!region) return;

    region.cities.push({
      name: city.name,
      latitude: numberOrDefault(city.latitude, 0),
      longitude: numberOrDefault(city.longitude, 0),
      population: numberOrDefault(city.population, 0),
      isCapital: !!city.isCapital
    });
  });

  return {
    generatedAt: new Date().toISOString(),
    schemaVersion: 'v1',
    provider: 'natural_earth + gadm + geonames (curated sample bootstrap)',
    countries: Object.keys(countriesMap).map(function (code) { return countriesMap[code]; })
  };
}

function run() {
  const countries = readJson('countries.json');
  const regions = readJson('regions.json');
  const cities = readJson('cities.json');

  const sql = buildSql(countries, regions, cities);
  fs.writeFileSync(outputSql, sql, 'utf8');

  const mapReady = buildMapReady(countries, regions, cities);
  fs.writeFileSync(outputMap, JSON.stringify(mapReady, null, 2) + '\n', 'utf8');

  console.log('Generated SQL:', path.relative(root, outputSql));
  console.log('Generated map JSON:', path.relative(root, outputMap));
  console.log('Countries:', countries.length, '| Regions:', regions.length, '| Cities:', cities.length);
}

run();
